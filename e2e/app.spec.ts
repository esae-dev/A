import { routineAction } from './actions'
import { expect, test, type Page } from '@playwright/test'

test.use({ timezoneId: 'Asia/Seoul' })

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-26T12:00:00+09:00'))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: '오늘의 루틴' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'AEHA', exact: true })).toBeVisible()
  await expect(page).toHaveTitle('오늘의 루틴 · AEHA')
  await expect(page.getByRole('button', { name: '루틴 추가', exact: true }).first()).toBeVisible()
})

async function addRoutine(page: Page, name: string) {
  await page.getByRole('button', { name: '루틴 추가', exact: true }).first().click()
  await page.getByLabel('습관 이름').fill(name)
  await page.getByRole('button', { name: '만들기', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  return page.locator('.routine-card').filter({ has: page.getByRole('heading', { name, exact: true }) })
}

test('create, check, undo, reload, edit and delete an actual local routine', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const card = await addRoutine(page, '책 10쪽 읽기')
  await card.getByRole('button', { name: '책 10쪽 읽기 완료하기' }).click()
  await expect(card.getByRole('button', { name: '책 10쪽 읽기 완료 취소' })).toHaveAttribute('aria-pressed', 'true')
  await card.getByRole('button', { name: '책 10쪽 읽기 완료 취소' }).click()
  await expect(card.getByRole('button', { name: '책 10쪽 읽기 완료하기' })).toHaveAttribute('aria-pressed', 'false')
  await card.getByRole('button', { name: '책 10쪽 읽기 완료하기' }).click()
  // The check is optimistic; enabled again means the write and snapshot finished.
  await expect(card.getByRole('button', { name: '책 10쪽 읽기 완료 취소' })).toBeEnabled()
  await page.reload()
  await expect(page.getByRole('button', { name: '책 10쪽 읽기 완료 취소' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '스트릭', exact: true }).click()
  await expect(page.locator('.streak-value.current')).toHaveText('1회')
  await expect(page.locator('.heatmap-grid .completed')).toHaveCount(1)
  await page.getByRole('button', { name: '홈', exact: true }).click()
  await routineAction(page, '책 10쪽 읽기', 'edit', 'ko', false)
  await page.getByLabel('습관 이름').fill('책 20쪽 읽기')
  await page.getByLabel('메모').fill('잠들기 전에')
  await expect(page.getByLabel('카테고리')).toHaveCount(0)
  await page.getByRole('button', { name: 'Fresh Mint', exact: true }).click()
  await page.getByRole('button', { name: '변경 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '책 20쪽 읽기' })).toBeVisible()
  await expect(page.getByText('잠들기 전에')).toBeVisible()
  await routineAction(page, '책 20쪽 읽기', 'delete')
  await page.getByRole('button', { name: '삭제', exact: true }).click()
  await expect(page.locator('.routine-card')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: '루틴 없음' })).toBeVisible()
  expect(errors).toEqual([])
})

