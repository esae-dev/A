test('project subpath manifest, icons, service worker and offline read/write', async ({ page, context }) => {
  const failed: string[] = []
  page.on('response', response => { if (response.status() >= 400) failed.push(response.url()) })
  await addRoutine(page, '오프라인 독서')
  const manifestURL = await page.locator('link[rel="manifest"]').getAttribute('href')
  expect(manifestURL).toBe('/A/manifest.webmanifest')
  const response = await page.request.get(manifestURL!)
  const manifest = await response.json()
  expect(manifest.id).toBe('/A/')
  expect(manifest.background_color).toBe('#f6f5f3')
  expect(manifest.theme_color).toBe('#f6f5f3')
  expect(manifest.start_url).toBe('/A/')
  expect(manifest.name).toBe('AEHA')
  expect(manifest.short_name).toBe('AEHA')
  await expect(page.locator('meta[name="apple-mobile-web-app-title"]')).toHaveAttribute('content', 'AEHA')
  expect(manifest.scope).toBe('/A/')
  expect(manifest.display).toBe('standalone')
  for (const icon of manifest.icons) {
    const result = await page.request.get(`/A/${icon.src}`)
    expect(result.status()).toBe(200)
    const png = await result.body()
    const size = Number(icon.sizes.split('x')[0])
    expect(png.readUInt32BE(16)).toBe(size)
    expect(png.readUInt32BE(20)).toBe(size)
  }
  for (const path of ['favicon.svg', 'favicon-32.png', 'apple-touch-icon.png', 'brand/logo-light.svg', 'brand/logo-dark.svg', 'brand/symbol-light.svg', 'brand/symbol-dark.svg']) {
    expect((await page.request.get(`/A/${path}`)).status()).toBe(200)
  }
  const scope = await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)
  expect(new URL(scope).pathname).toBe('/A/')
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: '오프라인 독서' })).toBeVisible()
  await expect.poll(() => page.locator('.brand-logo-light').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  await page.getByRole('button', { name: '설정', exact: true }).click()
  await page.getByRole('button', { name: '다크', exact: true }).click()
  await expect.poll(() => page.locator('.brand-logo-dark').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  await page.getByRole('button', { name: '홈', exact: true }).click()
  await page.getByRole('button', { name: '오프라인 독서 완료하기' }).click()
  await expect(page.getByRole('button', { name: '오프라인 독서 완료 취소' })).toBeVisible()
  await addRoutine(page, '오프라인 메모')
  await page.reload()
  await expect(page.getByRole('heading', { name: '오프라인 메모' })).toBeVisible()
  await expect(page.getByRole('button', { name: '오프라인 독서 완료 취소' })).toBeVisible()
  await context.setOffline(false)
  expect(failed).toEqual([])
})
